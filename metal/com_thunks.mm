// Synthetic VA allocator in high reserved synthetic range [0xF00000000000, 0xF00000100000)
// Guaranteed disjoint from all guest Mach-O __TEXT/__DATA VAs and ARM64 heap/stack pointers.
static std::atomic<uint64_t> g_next_com_va{0xF00000000000ULL};
static std::mutex g_reg_mtx;

uint64_t bo3_com_register_thunk(GuestFn fn) {
    uint64_t va = g_next_com_va.fetch_add(8ULL, std::memory_order_relaxed);
    if (va >= 0xF00000100000ULL) {
        fprintf(stderr, "[com_thunks] FATAL: synthetic VA pool exhausted!\n");
        abort();
    }
    std::lock_guard<std::mutex> lk(g_reg_mtx);
    bo3_register_fn(va, fn);
    return va;
}

// IUnknown slots 0..2
static SHIM_DEF(com_iunknown_qi) {
    SHIM_UNUSED_ALL();
    Bo3ComBase *obj = (Bo3ComBase *)rdi;
    const Bo3GUID *riid = (const Bo3GUID *)rsi;
    void **ppv = (void **)rdx;
    if (!obj || !ppv) return ret_u64(BO3_E_POINTER);
    return ret_u64(obj->query_interface(riid, ppv));
}

static SHIM_DEF(com_iunknown_addref) {
    SHIM_UNUSED_ALL();
    Bo3ComBase *obj = (Bo3ComBase *)rdi;
    if (!obj) return ret_u64(0);
    return ret_u64((uint32_t)obj->add_ref());
}

static SHIM_DEF(com_iunknown_release) {
    SHIM_UNUSED_ALL();
    Bo3ComBase *obj = (Bo3ComBase *)rdi;
    if (!obj) return ret_u64(0);
    return ret_u64((uint32_t)obj->release());
}

// Generic unimplemented-slot tracer: encodes slot index 0..127 via template instantiation.
// Hit counts are keyed per (interface name, slot) so one noisy interface never hides another
// interface's first unimplemented call on the same slot index.
static std::mutex g_trace_mtx;
static std::map<std::pair<const char *, int>, uint32_t> *g_trace_hits = nullptr;

template <int SLOT>
static GuestRet com_unimpl_slot(SHIM_PARAMS) {
    SHIM_UNUSED_ALL();
    Bo3ComBase *obj = (Bo3ComBase *)rdi;
    const char *name = (obj && obj->debug_name) ? obj->debug_name : "COM";
    std::lock_guard<std::mutex> lk(g_trace_mtx);
    if (!g_trace_hits) g_trace_hits = new std::map<std::pair<const char *, int>, uint32_t>();
    uint32_t n = (*g_trace_hits)[std::make_pair(name, SLOT)]++;
    if (n < 3) {
        fprintf(stderr, "[COM_UNIMPL] %s::slot%d (+0x%x) this=%p rsi=0x%llx rdx=0x%llx rcx=0x%llx\n",
                name, SLOT, SLOT * 8, (void *)obj,
                (unsigned long long)rsi, (unsigned long long)rdx, (unsigned long long)rcx);
        fflush(stderr);
    }
    return ret_u64(BO3_S_OK);
}

static uint64_t g_unimpl_slot_vas[128];
static uint64_t g_iunk_qi_va = 0;
static uint64_t g_iunk_addref_va = 0;
static uint64_t g_iunk_release_va = 0;

template <int N>
static void reg_unimpl_range() {
    if constexpr (N > 0) {
        reg_unimpl_range<N - 1>();
        g_unimpl_slot_vas[N - 1] = bo3_com_register_thunk(com_unimpl_slot<N - 1>);
    }
}

static void ensure_common_thunks() {
    static std::once_flag once;
    std::call_once(once, []() {
        g_iunk_qi_va      = bo3_com_register_thunk(com_iunknown_qi);
        g_iunk_addref_va  = bo3_com_register_thunk(com_iunknown_addref);
        g_iunk_release_va = bo3_com_register_thunk(com_iunknown_release);
        reg_unimpl_range<128>();
    });
}

void bo3_com_init_vtable(uint64_t *vtable, int num_slots, const char *iface_name) {
    (void)iface_name;
    ensure_common_thunks();
    for (int i = 0; i < num_slots; i++) {
        vtable[i] = g_unimpl_slot_vas[i < 128 ? i : 127];
    }
    if (num_slots > 0) vtable[0] = g_iunk_qi_va;
    if (num_slots > 1) vtable[1] = g_iunk_addref_va;
    if (num_slots > 2) vtable[2] = g_iunk_release_va;
}

bool bo3_guid_eq(const Bo3GUID *a, const Bo3GUID *b) {
    if (!a || !b) return false;
    return memcmp(a, b, sizeof(Bo3GUID)) == 0;
}

